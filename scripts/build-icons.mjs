const icons = {};
const missing = [];

const defaultAttributes = {
  xmlns: 'http://www.w3.org/2000/svg',
  width: 24,
  height: 24,
  viewBox: '0 0 24 24',
  fill: 'none',
  stroke: 'currentColor',
  'stroke-width': 2,
  'stroke-linecap': 'round',
  'stroke-linejoin': 'round'
};

for (const name of NAMES) {
  const file = join(iconsDir, `${name}.js`);
  if (!existsSync(file)) {
    missing.push(name);
    continue;
  }
  const src = readFileSync(file, 'utf8');
  const start = src.indexOf('[');
  const end = src.lastIndexOf(']') + 1;
  const literal = src.slice(start, end);
  // eslint-disable-next-line no-eval
  icons[name] = eval(literal);
}

if (missing.length) {
  console.warn('Missing icons (skipped):', missing.join(', '));
}

const output = `// Auto-generated by scripts/build-icons.mjs - do not edit by hand.
// Lucide v0.452.0 subset (ISC license).
const defaultAttributes = {
  xmlns: 'http://www.w3.org/2000/svg',
  width: 24,
  height: 24,
  viewBox: '0 0 24 24',
  fill: 'none',
  stroke: 'currentColor',
  'stroke-width': 2,
  'stroke-linecap': 'round',
  'stroke-linejoin': 'round'
};

const ICONS = ${JSON.stringify(icons)};

const createElement = (tag, attrs, children = []) => {
  const element = document.createElementNS('http://www.w3.org/2000/svg', tag);
  Object.keys(attrs).forEach((name) => element.setAttribute(name, String(attrs[name])));
  children.forEach((child) => element.appendChild(createElement(...child)));
  return element;
};

const getAttrs = (element) =>
  Array.from(element.attributes).reduce((attrs, attr) => {
    attrs[attr.name] = attr.value;
    return attrs;
  }, {});

const combineClassNames = (list) => {
  const classes = list
    .flatMap((c) => (typeof c === 'string' ? c.split(' ') : c && c.class ? String(c.class).split(' ') : []))
    .map((c) => c.trim())
    .filter(Boolean);
  return Array.from(new Set(classes)).join(' ');
};

function createIcons(options = {}) {
  const { attrs = {}, nameAttr = 'data-lucide', icons = ICONS, root = document } = options;
  root.querySelectorAll('[' + nameAttr + ']').forEach((element) => {
    const name = element.getAttribute(nameAttr);
    const iconNode = icons[name];
    if (!iconNode) return;
    const elementAttrs = getAttrs(element);
    const [tag, iconAttributes, children] = iconNode;
    const iconAttrs = { ...iconAttributes, ...attrs, ...elementAttrs };
    delete iconAttrs[nameAttr];
    const className = combineClassNames(['lucide', 'lucide-' + name, elementAttrs, attrs]);
    if (className) iconAttrs.class = className;
    element.parentNode.replaceChild(createElement(tag, iconAttrs, children), element);
  });
}

export { createIcons, ICONS as icons };
`;

const outDir = join(root, 'vendor');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'lucide-subset.js'), output);
console.log(`Wrote vendor/lucide-subset.js with ${Object.keys(icons).length} icons (${output.length} bytes).`);
